# ─── AC-16 · no external HTTP calls made by any brief ─────────────────


async def test_daily_brief_ac_16_no_external_http(
    db_session: AsyncSession, seed_tenant: Tenant, monkeypatch
) -> None:
    """Guard against a future 'nice-to-have' Notion/Slack sink getting
    silently smuggled into the pipeline."""
    constructed: list[str] = []
    import httpx

    class _Sentinel(httpx.AsyncClient):
        def __init__(self, *a, **k):  # type: ignore[no-untyped-def]
            constructed.append("httpx.AsyncClient built")
            super().__init__(*a, **k)

    monkeypatch.setattr(httpx, "AsyncClient", _Sentinel)

    await run_today_top5(
        session=db_session,
        now=_now_tpe(2026, 6, 27, 9),
        sink=NullSink(),
        retrieval=_fake_retrieval(),
        llm=_fake_llm(),
        tenant_id=seed_tenant.id,
    )
    assert constructed == []


