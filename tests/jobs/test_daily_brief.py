# ─── AC-8 · weekly_review anchors to Friday even if misfired Sat ─────


def test_daily_brief_ac_08_weekly_review_friday_anchor() -> None:
    fri = _business_date("weekly_review", _now_tpe(2026, 6, 26, 17))  # Fri
    sat = _business_date("weekly_review", _now_tpe(2026, 6, 27, 9))  # Sat (misfire)
    thu = _business_date("weekly_review", _now_tpe(2026, 6, 25, 17))  # Thu (early)
