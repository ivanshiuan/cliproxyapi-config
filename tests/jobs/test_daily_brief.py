# ─── AC-10 · FileSink atomic — no leftover .tmp on write failure ─────


async def test_daily_brief_ac_10_filesink_write_failure(
    db_session: AsyncSession, seed_tenant: Tenant, tmp_path: Path, monkeypatch
) -> None:
    sink = FileSink("MORNING_BRIEF.md", repo_root=tmp_path)

    def _boom(*_a, **_k):
        raise OSError("disk full")

    monkeypatch.setattr("os.replace", _boom)

    with pytest.raises(BriefSinkError):
        await run_today_top5(
            session=db_session,
            now=_now_tpe(2026, 6, 27, 9),
            sink=sink,
            retrieval=_fake_retrieval(),
            llm=_fake_llm(),
            tenant_id=seed_tenant.id,
        )
    # No lingering .tmp file
    leftovers = list(tmp_path.glob("*.tmp"))
    assert leftovers == []


