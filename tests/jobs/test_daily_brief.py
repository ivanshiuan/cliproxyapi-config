# ─── AC-5 · failure then retry updates same row ──────────────────────


async def test_daily_brief_ac_05_failure_then_retry(
    db_session: AsyncSession, seed_tenant: Tenant, tmp_path: Path
) -> None:
    llm_bad = FakeLLMClient(fail_on_call=1)
    first = await run_today_top5(
        session=db_session,
        now=_now_tpe(2026, 6, 27, 9),
        sink=NullSink(),
        retrieval=_fake_retrieval(),
        llm=llm_bad,
        tenant_id=seed_tenant.id,
    )
    assert first.status == "failed"
    assert first.error_message and "LLM boom" in first.error_message

    # Retry same day same prompt version — should update the same row.
    llm_ok = _fake_llm()
    second = await run_today_top5(
        session=db_session,
        now=_now_tpe(2026, 6, 27, 9),
        sink=NullSink(),
        retrieval=_fake_retrieval(),
        llm=llm_ok,
        tenant_id=seed_tenant.id,
    )
    assert second.status == "completed"
    assert second.brief_run_id == first.brief_run_id

    rows = (
        await db_session.execute(
            select(BriefRun).where(BriefRun.tenant_id == seed_tenant.id)
        )
    ).scalars().all()
    assert len(rows) == 1


