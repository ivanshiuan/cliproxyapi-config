# ─── helpers ──────────────────────────────────────────────────────────


def _hits(n: int = 3) -> list[RetrievedChunk]:
    return [
        RetrievedChunk(
            chunk_id=uuid.uuid4(),
            document_id=uuid.uuid4(),
            text=f"chunk-{i} 內容 {i}",
            score=0.9 - i * 0.05,
            section_path=f"Section > Sub {i}",
        )
        for i in range(n)
    ]


def _fake_llm(text: str = "# BRIEF\n\nTL;DR: ok\n\n- item 1") -> FakeLLMClient:
    return FakeLLMClient(reply=text)


def _fake_retrieval(hits: list[RetrievedChunk] | None = None) -> FakeRetrievalClient:
    return FakeRetrievalClient(chunks=list(hits) if hits is not None else _hits(3))


def _now_tpe(y: int, m: int, d: int, h: int = 9) -> datetime:
    return datetime(y, m, d, h, 0, 0, tzinfo=TPE).astimezone(UTC)


# ─── AC-1 · today_top5 happy path ────────────────────────────────────


async def test_daily_brief_ac_01_happy_path(
    db_session: AsyncSession, seed_tenant: Tenant, tmp_path: Path
) -> None:
    result = await run_today_top5(
        session=db_session,
        now=_now_tpe(2026, 6, 27, 9),
        sink=FileSink("MORNING_BRIEF.md", repo_root=tmp_path),
        retrieval=_fake_retrieval(),
        llm=_fake_llm("# 今日重點\n\nTL;DR: X"),
        tenant_id=seed_tenant.id,
    )
    assert result.status == "completed"
    row = (
        await db_session.execute(select(BriefRun).where(BriefRun.id == result.brief_run_id))
    ).scalar_one()
    assert row.brief_kind == "today_top5"
    assert row.output_path == "MORNING_BRIEF.md"

    on_disk = (tmp_path / "MORNING_BRIEF.md").read_text(encoding="utf-8")
    assert "auto-generated by daily_brief.today_top5" in on_disk
    assert "# 今日重點" in on_disk


# ─── AC-2 · idempotent on same day + same prompt version ──────────────


async def test_daily_brief_ac_02_idempotent(
    db_session: AsyncSession, seed_tenant: Tenant, tmp_path: Path
) -> None:
    llm = _fake_llm()
    retr = _fake_retrieval()
    kw = dict(
        session=db_session,
        now=_now_tpe(2026, 6, 27, 9),
        sink=NullSink(),
        retrieval=retr,
        llm=llm,
        tenant_id=seed_tenant.id,
    )
    first = await run_today_top5(**kw)
    second = await run_today_top5(**kw)
    assert first.status == "completed"
    assert second.status == "skipped_duplicate"
    assert second.brief_run_id == first.brief_run_id
    # LLM called exactly once
    assert len(llm.calls) == 1


# ─── AC-3 · prompt bump triggers re-run ──────────────────────────────


async def test_daily_brief_ac_03_prompt_bump_reruns(
    db_session: AsyncSession, seed_tenant: Tenant, monkeypatch
) -> None:
    llm = _fake_llm()
    retr = _fake_retrieval()
    kw = dict(
        session=db_session,
        now=_now_tpe(2026, 6, 27, 9),
        sink=NullSink(),
        retrieval=retr,
        llm=llm,
        tenant_id=seed_tenant.id,
    )
    first = await run_today_top5(**kw)
    assert first.status == "completed"

    # Bump the prompt version — simulate a v1 → v2 revision.
    monkeypatch.setitem(
        _VERSION_MAP,
        "today_top5",
        ("today_top5/v2", _VERSION_MAP["today_top5"][1] + "\n\nv2 tweak"),
    )
    second = await run_today_top5(**kw)
    assert second.status == "completed"
    assert second.prompt_template_version == "today_top5/v2"
    assert second.brief_run_id != first.brief_run_id
    assert len(llm.calls) == 2


